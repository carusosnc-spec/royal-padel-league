-- Royal Bet Lab: automatic per-set winner markets and winning-wager push queue.
-- Markets use the already-computed historical predictions for each upcoming set.
CREATE TABLE IF NOT EXISTS public.rpl_bet_win_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wager_id bigint NOT NULL UNIQUE REFERENCES public.rpl_bet_wagers(id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
  market_id bigint NOT NULL REFERENCES public.rpl_bet_markets(id) ON DELETE CASCADE,
  payout_credits integer NOT NULL CHECK (payout_credits > 0),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','sent','skipped')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz
);
ALTER TABLE public.rpl_bet_win_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.rpl_bet_win_notifications FROM anon, authenticated;

CREATE INDEX IF NOT EXISTS rpl_bet_win_notifications_pending_idx
  ON public.rpl_bet_win_notifications(status, next_attempt_at, created_at);

CREATE OR REPLACE FUNCTION public.rpl_queue_bet_win_notification()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
BEGIN
  IF NEW.status = 'won'
     AND OLD.status IS DISTINCT FROM NEW.status
     AND COALESCE(NEW.settled_payout, 0) > 0 THEN
    INSERT INTO public.rpl_bet_win_notifications
      (wager_id, player_id, market_id, payout_credits)
    VALUES
      (NEW.id, NEW.player_id, NEW.market_id, NEW.settled_payout)
    ON CONFLICT (wager_id) DO NOTHING;
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS rpl_bet_wager_win_notification_trigger ON public.rpl_bet_wagers;
CREATE TRIGGER rpl_bet_wager_win_notification_trigger
AFTER UPDATE OF status, settled_payout ON public.rpl_bet_wagers
FOR EACH ROW
WHEN (NEW.status = 'won' AND OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.rpl_queue_bet_win_notification();

-- Upsert the two possible winners for a predicted set. Quotes are sourced from
-- rpl_bet_predictions, whose odds are calculated from confirmed historical sets.
CREATE OR REPLACE FUNCTION public.rpl_sync_set_winner_markets_for_prediction(p_prediction_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_pred public.rpl_bet_predictions%ROWTYPE;
  v_scheduled_at timestamptz;
  v_result_match_id bigint;
  v_a1 text;
  v_a2 text;
  v_b1 text;
  v_b2 text;
BEGIN
  SELECT * INTO v_pred
  FROM public.rpl_bet_predictions
  WHERE id = p_prediction_id;
  IF NOT FOUND OR v_pred.actual_games_a IS NOT NULL
     OR v_pred.actual_games_b IS NOT NULL OR v_pred.settled_at IS NOT NULL THEN
    RETURN;
  END IF;

  SELECT cm.scheduled_at, cm.result_match_id
  INTO v_scheduled_at, v_result_match_id
  FROM public.calendar_matches cm
  WHERE cm.id = v_pred.calendar_match_id;

  IF NOT FOUND OR v_scheduled_at <= now() OR v_result_match_id IS NOT NULL THEN
    RETURN;
  END IF;

  SELECT CASE WHEN NULLIF(trim(p.nickname), '') IS NOT NULL
    THEN p.name || ' “' || p.nickname || '”' ELSE p.name END
  INTO v_a1 FROM public.players p WHERE p.id = v_pred.pair_a_player_1;
  SELECT CASE WHEN NULLIF(trim(p.nickname), '') IS NOT NULL
    THEN p.name || ' “' || p.nickname || '”' ELSE p.name END
  INTO v_a2 FROM public.players p WHERE p.id = v_pred.pair_a_player_2;
  SELECT CASE WHEN NULLIF(trim(p.nickname), '') IS NOT NULL
    THEN p.name || ' “' || p.nickname || '”' ELSE p.name END
  INTO v_b1 FROM public.players p WHERE p.id = v_pred.pair_b_player_1;
  SELECT CASE WHEN NULLIF(trim(p.nickname), '') IS NOT NULL
    THEN p.name || ' “' || p.nickname || '”' ELSE p.name END
  INTO v_b2 FROM public.players p WHERE p.id = v_pred.pair_b_player_2;

  IF v_a1 IS NULL OR v_a2 IS NULL OR v_b1 IS NULL OR v_b2 IS NULL
     OR v_pred.probability_a <= 0 OR v_pred.probability_b <= 0
     OR v_pred.odds_a <= 1 OR v_pred.odds_b <= 1 THEN
    RETURN;
  END IF;

  INSERT INTO public.rpl_bet_markets AS existing (
    calendar_match_id, market_type, set_number, selection_key, selection_label,
    theoretical_probability, odds, status, opens_at, closes_at, market_scope,
    season_key, market_metadata
  )
  VALUES
  (
    v_pred.calendar_match_id, 'set_winner', v_pred.set_number, 'pair_a',
    'Coppia A: ' || v_a1 || ' + ' || v_a2,
    v_pred.probability_a, v_pred.odds_a, 'open', now(), v_scheduled_at, 'match',
    NULL, jsonb_build_object('source','rpl_bet_predictions','prediction_id',v_pred.id,
      'snapshot_date',v_pred.snapshot_date,'model_version',v_pred.model_version,'automatic',true)
  ),
  (
    v_pred.calendar_match_id, 'set_winner', v_pred.set_number, 'pair_b',
    'Coppia B: ' || v_b1 || ' + ' || v_b2,
    v_pred.probability_b, v_pred.odds_b, 'open', now(), v_scheduled_at, 'match',
    NULL, jsonb_build_object('source','rpl_bet_predictions','prediction_id',v_pred.id,
      'snapshot_date',v_pred.snapshot_date,'model_version',v_pred.model_version,'automatic',true)
  )
  ON CONFLICT (calendar_match_id, market_type, set_number, selection_key)
  DO UPDATE SET
    selection_label = EXCLUDED.selection_label,
    theoretical_probability = EXCLUDED.theoretical_probability,
    odds = EXCLUDED.odds,
    closes_at = EXCLUDED.closes_at,
    market_metadata = EXCLUDED.market_metadata,
    updated_at = now()
  WHERE existing.market_scope = 'match'
    AND existing.status = 'open'
    AND (
      existing.market_metadata->>'snapshot_date' IS NULL
      OR (existing.market_metadata->>'snapshot_date')::date <= v_pred.snapshot_date
    )
    AND NOT EXISTS (
      SELECT 1
      FROM public.rpl_bet_wagers w
      JOIN public.rpl_bet_markets m ON m.id = w.market_id
      WHERE m.calendar_match_id = v_pred.calendar_match_id
        AND m.market_type = 'set_winner'
        AND m.set_number = v_pred.set_number
    );
END;
$function$;

REVOKE ALL ON FUNCTION public.rpl_sync_set_winner_markets_for_prediction(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.rpl_sync_set_winner_markets_after_prediction()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
BEGIN
  PERFORM public.rpl_sync_set_winner_markets_for_prediction(NEW.id);
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS rpl_bet_prediction_sync_set_markets ON public.rpl_bet_predictions;
CREATE TRIGGER rpl_bet_prediction_sync_set_markets
AFTER INSERT OR UPDATE OF probability_a, probability_b, odds_a, odds_b,
  pair_a_player_1, pair_a_player_2, pair_b_player_1, pair_b_player_2,
  actual_games_a, actual_games_b, settled_at, snapshot_date
ON public.rpl_bet_predictions
FOR EACH ROW
EXECUTE FUNCTION public.rpl_sync_set_winner_markets_after_prediction();

-- Backfill only the newest unsolved prediction for each future set.
DO $function$
DECLARE
  v_prediction_id bigint;
BEGIN
  FOR v_prediction_id IN
    SELECT DISTINCT ON (p.calendar_match_id, p.set_number) p.id
    FROM public.rpl_bet_predictions p
    JOIN public.calendar_matches cm ON cm.id = p.calendar_match_id
    WHERE cm.scheduled_at > now()
      AND cm.result_match_id IS NULL
      AND p.actual_games_a IS NULL
      AND p.actual_games_b IS NULL
      AND p.settled_at IS NULL
    ORDER BY p.calendar_match_id, p.set_number, p.snapshot_date DESC, p.predicted_at DESC, p.id DESC
  LOOP
    PERFORM public.rpl_sync_set_winner_markets_for_prediction(v_prediction_id);
  END LOOP;
END;
$function$;
